export function SocialIcon({ label, className = 'w-4 h-4' }: { label: string; className?: string }) {
  const key = label.toLowerCase()
  if (key.includes('github')) return <GithubIcon className={className} />
  if (key.includes('linkedin')) return <LinkedinIcon className={className} />
  if (key.includes('tryhackme')) return <TryHackMeIcon className={className} />
  if (key.includes('medium')) return <MediumIcon className={className} />
  if (key.includes('instagram')) return <InstagramIcon className={className} />
  return <Globe className={className} />
}

export function TechBadgeIcon({ name, className = 'w-3.5 h-3.5' }: { name: string; className?: string }) {
  const n = name.toLowerCase()
  if (n.includes('python')) return <PythonIcon className={className} />
  if (n.includes('linux') || n.includes('bash') || n.includes('pentest')) return <Terminal className={className} />
  if (n.includes('fastapi') || n.includes('typescript') || n.includes('react')) return <Code2 className={className} />
  if (n.includes('ml') || n.includes('machine') || n.includes('cnn') || n.includes('mcp') || n.includes('agent'))
    return <Sparkles className={className} />
  if (n.includes('dns') || n.includes('network')) return <Network className={className} />
  if (n.includes('forensic') || n.includes('entropy')) return <FileSearch className={className} />
  if (n.includes('zero') || n.includes('privacy') || n.includes('hardening')) return <Lock className={className} />
  if (n.includes('threat') || n.includes('security') || n.includes('auditing')) return <ShieldAlert className={className} />
  if (n.includes('db') || n.includes('mongo')) return <Database className={className} />
  return <Cpu className={className} />
}
